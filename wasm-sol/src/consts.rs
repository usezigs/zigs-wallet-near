/// True if a `transact` of this many inputs and outputs has a circuit.
pub fn is_supported_shape(inputs: usize, outputs: usize) -> bool {
    SUPPORTED_SHAPES
        .iter()
        .any(|&(i, o)| usize::from(i) == inputs && usize::from(o) == outputs)
}

